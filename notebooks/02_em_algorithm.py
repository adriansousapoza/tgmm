    _colors_data = ['#e41a1c', '#ff7f00', '#984ea3', '#4daf4a']
    for _i in range(len(n_samples)):
        _mask = labels == _i
        plt.scatter(X[_mask, 0].cpu(), X[_mask, 1].cpu(), c=_colors_data[_i], s=10, alpha=0.5, label=legend_labels[_i])
    plt.title('Original Data with True Labels')
    plt.xlabel('X1')
    plt.ylabel('X2')
    plt.legend()
    # Convert to tensor
    # Initialize means for 4 components
    # Plot the original data
