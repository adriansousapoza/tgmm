@app.cell
def _(GaussianMixture, X, device, means_init, plot_2d_gmm_resp, plt):
    _fig, _axs = plt.subplots(3, 3, figsize=(18, 16), dpi=80)
    gmm_means = [means_init]
    n_plot = 0
    for _i in range(1000):
        gmm = GaussianMixture(n_features=2, n_components=4, covariance_type='full', init_means=means_init, device=device, tol=1e-06)
        if _i > 0:
            gmm.fit(X, max_iter=_i)
        else:
            gmm._allocate_parameters(X)
        responsibilities, _ = gmm._e_step(X)
        gmm._m_step(X, responsibilities)  # For i=0, allocate parameters but don't run EM
        gmm_means.append(gmm.means_)
        if _i == 1 or _i == 5 or gmm.converged_:
            plot_2d_gmm_resp(gmm, X, responsibilities, _i, _fig, _axs, n_plot, gmm_means)
            n_plot += 1
            if gmm.converged_:
                break
    plt.tight_layout()
    plt.gcf()
    return


