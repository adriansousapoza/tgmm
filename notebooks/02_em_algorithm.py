@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## The Model: A Mixture of Gaussians

    A Gaussian Mixture Model assumes each data point was generated by first picking one of $K$
    components at random, then sampling from that component's Gaussian. Formally, introduce a
    hidden (latent) label $z_i \in \{1, \dots, K\}$ for each point $x_i$, with

    $$
    p(z_i = k) = \pi_k, \qquad \sum_{k=1}^K \pi_k = 1,
    $$

    and, given the label,

    $$
    p(x_i \mid z_i = k) = \mathcal{N}(x_i \mid \mu_k, \Sigma_k).
    $$

    Marginalizing out the unobserved label gives the density we actually fit to data:

    $$
    p(x_i \mid \theta) = \sum_{k=1}^K \pi_k \, \mathcal{N}(x_i \mid \mu_k, \Sigma_k),
    \qquad \theta = \{\pi_k, \mu_k, \Sigma_k\}_{k=1}^K .
    $$

    Maximum likelihood estimation asks for the $\theta$ that makes the observed data most probable:

    $$
    \theta^\star = \arg\max_\theta \; \sum_{i=1}^N \log \sum_{k=1}^K \pi_k \, \mathcal{N}(x_i \mid \mu_k, \Sigma_k).
    $$

    The sum *inside* the logarithm is the obstacle: unlike a single Gaussian, there is no
    closed-form solution for $\theta^\star$. **Expectation-Maximization (EM)** sidesteps this by
    treating the labels $z_i$ as auxiliary variables and optimizing iteratively instead of directly.
    """)
    return


@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## The EM Algorithm

    Each EM iteration alternates two steps.

    ### E-step: soft-assign points to components

    Using Bayes' rule, compute the posterior probability ("responsibility") that component $k$
    generated point $x_i$, under the *current* parameters:

    $$
    \gamma_{ik} \;=\; p(z_i = k \mid x_i, \theta) \;=\;
    \frac{\pi_k \, \mathcal{N}(x_i \mid \mu_k, \Sigma_k)}
         {\displaystyle\sum_{j=1}^K \pi_j \, \mathcal{N}(x_i \mid \mu_j, \Sigma_j)}.
    $$

    Each row of $\gamma$ sums to 1: this is a *soft*, probabilistic cluster assignment, not a hard
    one. This is exactly what `GaussianMixture._e_step` computes.

    ### M-step: re-estimate parameters from the soft assignments

    Treat $\gamma_{ik}$ as weights and re-fit each component to the (weighted) points assigned to
    it:

    $$
    N_k = \sum_{i=1}^N \gamma_{ik} \qquad \text{(effective number of points in component $k$)}
    $$

    $$
    \pi_k = \frac{N_k}{N}, \qquad
    \mu_k = \frac{1}{N_k}\sum_{i=1}^N \gamma_{ik}\, x_i, \qquad
    \Sigma_k = \frac{1}{N_k}\sum_{i=1}^N \gamma_{ik} (x_i - \mu_k)(x_i - \mu_k)^\top .
    $$

    This is `GaussianMixture._m_step` (`tgmm` additionally adds a small `reg_covar` to the diagonal of each $\Sigma_k$ to keep it positive definite). Notice these are just the ordinary Gaussian MLE formulas
    (sample mean, sample covariance, class proportion) with each point weighted by $\gamma_{ik}$
    instead of being hard-assigned to one component.

    ### Repeat until convergence

    Alternate E-step and M-step until the log-likelihood

    $$
    \ell(\theta) = \sum_{i=1}^N \log \sum_{k=1}^K \pi_k \, \mathcal{N}(x_i \mid \mu_k, \Sigma_k)
    $$

    stops improving by more than `tol` -- tracked in `tgmm` as `gmm.lower_bound_`.
    """)
    return


@app.cell(hide_code=True)
def _(mo):
    mo.md(r"""
    ## Why Does It Work?

    Each EM iteration is guaranteed to never *decrease* the log-likelihood $\ell(\theta)$.
    Intuitively:

    - The **E-step** computes the exact posterior $p(z \mid x, \theta)$. This makes a certain lower
      bound on $\log p(X \mid \theta)$ (the *evidence lower bound*, or ELBO) touch the true
      log-likelihood exactly, at the current $\theta$.
    - The **M-step** then maximizes that same lower bound over $\theta$. Since the bound was tight
      at the old parameters, the log-likelihood at the new parameters is at least as high as
      before.

    This guarantees **monotonic improvement**, but only to a **local** optimum -- the point EM
    converges to depends on where it starts (see the
    [GMM Initializer guide](../user-guide/gmm-initializer.md) for the initialization strategies
    `tgmm` provides). To make that dependence -- and the iterative improvement itself -- easy to
    see, this notebook deliberately starts EM from a poor initial guess and watches it recover.

    The rest of the notebook works through this concretely: first a simple 1D example where we can
    plot the fitted Gaussians directly against the data, then a fuller 2D example with four
    differently-shaped clusters.
    """)
    return


