@app.cell
def _(
    GaussianMixture,
    X_1d,
    data,
    initial_covariances,
    initial_means,
    initial_weights,
    norm,
    np,
    plt,
    real_means,
    real_stds,
    torch,
    tqdm,
):
    num_steps = 1000
    #num_steps = 10 #for testing
    gmm_full = GaussianMixture(n_features=1, n_components=3, covariance_type='full', init_means=initial_means, init_covariances=initial_covariances, init_weights=initial_weights, device='cpu', max_iter=num_steps, verbose=False)
    # Create GMM and fit with full EM
    means = np.zeros((num_steps + 1, 3))
    stds = np.zeros((num_steps + 1, 3))
    taus = np.zeros((num_steps + 1, 3))
    means[0] = initial_means.squeeze().numpy()
    stds[0] = [2.5, 2.5, 2.5]
    taus[0] = initial_weights.numpy()
    for step in tqdm(range(num_steps)):
        gmm_step = GaussianMixture(n_features=1, n_components=3, covariance_type='full', init_means=torch.tensor(means[step].reshape(-1, 1), dtype=torch.float32), init_covariances=torch.tensor([[[stds[step][i] ** 2]] for i in range(3)], dtype=torch.float32), init_weights=torch.tensor(taus[step], dtype=torch.float32), device='cpu', max_iter=1)
        gmm_step.fit(X_1d)
        means[step + 1] = gmm_step.means_.squeeze().cpu().numpy()
        stds[step + 1] = torch.sqrt(gmm_step.covariances_[:, 0, 0]).cpu().numpy()
        taus[step + 1] = gmm_step.weights_.cpu().numpy()
    # Track parameters over iterations
        if gmm_step.converged_:
            break
    gmm_full = gmm_step
    mean_range = np.linspace(min(data), max(data), 50)
    std_range = np.linspace(0.01, 5, 50)

    def log_likelihood(data, means_np, stds_np, taus_np):
        likelihood = np.zeros((data.shape[0], len(means_np)))
    # Fit one iteration at a time to track progress
        for i in range(len(means_np)):
            likelihood[:, i] = norm.pdf(data, means_np[i], stds_np[i])  # Create a new GMM for this iteration
        total_likelihood = np.dot(likelihood, taus_np)
        return np.sum(np.log(total_likelihood))
    log_likelihoods_mean1_std1 = np.zeros((len(std_range), len(mean_range)))
    log_likelihoods_mean2_std2 = np.zeros((len(std_range), len(mean_range)))
    log_likelihoods_mean3_std3 = np.zeros((len(std_range), len(mean_range)))
    for _i, _m in enumerate(mean_range):
        for _j, _s in enumerate(std_range):
            means_1 = [_m, means[-1, 1], means[-1, 2]]
            stds_1 = [_s, stds[-1, 1], stds[-1, 2]]
            means_2 = [means[-1, 0], _m, means[-1, 2]]
            stds_2 = [stds[-1, 0], _s, stds[-1, 2]]
            means_3 = [means[-1, 0], means[-1, 1], _m]
            stds_3 = [stds[-1, 0], stds[-1, 1], _s]
            taus_ll = [taus[-1, 0], taus[-1, 1], taus[-1, 2]]  # Store parameters
            log_likelihoods_mean1_std1[_j, _i] = log_likelihood(data, means_1, stds_1, taus_ll)
            log_likelihoods_mean2_std2[_j, _i] = log_likelihood(data, means_2, stds_2, taus_ll)
            log_likelihoods_mean3_std3[_j, _i] = log_likelihood(data, means_3, stds_3, taus_ll)
    _fig, _axs = plt.subplots(1, 3, figsize=(20, 5))
    cs = _axs[0].contourf(mean_range, std_range, log_likelihoods_mean1_std1, cmap='viridis')
    cbar = _fig.colorbar(cs, ax=_axs[0])
    cbar.ax.set_ylabel('Log-Likelihood')
    # Use the last fitted GMM for visualization
    _axs[0].set_title('Log-Likelihood vs. Mean1 and Std1')
    _axs[0].set_ylabel('Standard Deviation')
    # Range of parameter values for plotting
    _axs[0].set_xlabel('Mean')
    _axs[0].scatter(real_means[0], real_stds[0], color='red', label='Real Mean1 and Std1', s=50, marker='o')
    _axs[0].scatter(means[0, 0], stds[0, 0], color='red', label='Initial Mean1 and Std1', s=100, marker='*')
    # Log likelihood function for visualization
    _axs[0].plot(means[:, 0], stds[:, 0], color='magenta', label='Estimated Mean1 and Std1')
    _axs[0].legend()
    cs = _axs[1].contourf(mean_range, std_range, log_likelihoods_mean2_std2, cmap='viridis')
    cbar = _fig.colorbar(cs, ax=_axs[1])
    cbar.ax.set_ylabel('Log-Likelihood')
    _axs[1].set_title('Log-Likelihood vs. Mean2 and Std2')
    _axs[1].set_ylabel('Standard Deviation')
    # Compute log-likelihood for different parameter values
    _axs[1].set_xlabel('Mean')
    _axs[1].scatter(real_means[1], real_stds[1], color='red', label='Real Mean2 and Std2', s=50, marker='o')
    _axs[1].scatter(means[0, 1], stds[0, 1], color='red', label='Initial Mean2 and Std2', s=100, marker='*')
    _axs[1].plot(means[:, 1], stds[:, 1], color='magenta', label='Estimated Mean2 and Std2')
    _axs[1].legend()
    cs = _axs[2].contourf(mean_range, std_range, log_likelihoods_mean3_std3, cmap='viridis')
    cbar = _fig.colorbar(cs, ax=_axs[2])
    cbar.ax.set_ylabel('Log-Likelihood')
    _axs[2].set_title('Log-Likelihood vs. Mean3 and Std3')
    _axs[2].set_ylabel('Standard Deviation')
    _axs[2].set_xlabel('Mean')
    _axs[2].scatter(real_means[2], real_stds[2], color='red', label='Real Mean3 and Std3', s=50, marker='o')
    _axs[2].scatter(means[0, 2], stds[0, 2], color='red', label='Initial Mean3 and Std3', s=100, marker='*')
    _axs[2].plot(means[:, 2], stds[:, 2], color='magenta', label='Estimated Mean3 and Std3')
    _axs[2].legend()
    plt.tight_layout()
    plt.gcf()
    return (gmm_full,)


